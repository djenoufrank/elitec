const TRANSLATIONS = { fr: FR, en: EN };

const I18nContext = createContext({ lang: "fr", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem("elitec_lang") || "fr"; } catch { return "fr"; }
  });
  const setLang = (l) => {
    setLangState(l);
    try { localStorage.setItem("elitec_lang", l); } catch {}
  };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = (key) => (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}
